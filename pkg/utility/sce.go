// getSCENBTExportRate returns the export rate for SCE Net Billing Tariff (NEM 3.0)
// for a given time.
func getSCENBTExportRate(t time.Time) float64 {
	year := t.Year()
	if year < 2026 {
		year = 2026
	} else if year > 2027 {
		year = 2027
	}

	monthStr := t.Format("Jan")

	// Determine if weekend or holiday
	isWeekend := t.Weekday() == time.Saturday || t.Weekday() == time.Sunday
	if !isWeekend {
		// SCE holidays
		holidays := getSCEHolidays(year)
		dateStr := t.Format("2006-01-02")
		for _, h := range holidays {
			if h == dateStr {
				isWeekend = true
				break
			}
		}
	}

	dayType := "Weekday"
	if isWeekend {
		dayType = "Weekend"
	}

	key := fmt.Sprintf("%s_%s_%d", monthStr, dayType, t.Hour())

	if yearMap, ok := sceNBTData[year]; ok {
		if val, ok := yearMap[key]; ok {
			return val
		}
	}

	// Fallback to 2026 if not found
	if val, ok := sceNBTData[2026][key]; ok {
		return val
	}
	return 0.05 // safe fallback
}

// getSCEHolidays calculates designated holidays for SCE.
// According to Southern California Edison's official rate schedules (e.g., TOU-D tariffs,
// source: https://www.sce.com/tariffbooks), the following 8 holidays are observed:
// 1. New Year's Day (January 1)
// 2. Presidents' Day (Third Monday in February)
// 3. Memorial Day (Last Monday in May)
// 4. Independence Day (July 4)
// 5. Labor Day (First Monday in September)
// 6. Veterans Day (November 11)
// 7. Thanksgiving Day (Fourth Thursday in November)
// 8. Christmas Day (December 25)
//
// Shift rules:
// - If a holiday falls on a Sunday, the following Monday is recognized as the holiday.
// - If a holiday falls on a Saturday, it is not shifted (Saturday is already treated as weekend).
func getSCEHolidays(year int) []string {
	// Helper to shift Sunday holiday to Monday
	shiftSCEHoliday := func(t time.Time) time.Time {
		if t.Weekday() == time.Sunday {
			return t.AddDate(0, 0, 1)
		}
		return t
	}

	holidays := []time.Time{
		shiftSCEHoliday(newYearsDay(year)),
		shiftSCEHoliday(presidentsDay(year)),
		memorialDay(year),
		shiftSCEHoliday(independenceDay(year)),
		laborDay(year),
		shiftSCEHoliday(veteransDay(year)),
		thanksgivingDay(year),
		shiftSCEHoliday(christmasDay(year)),
	}

	return formatHolidays(holidays, year)
}

