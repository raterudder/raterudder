// sceACCPlusAdderDollarsPerKWH returns the residential non-equity 9-year ACC Plus adder ($/kWh)
// from Schedule NBT Sheet 7 (Cal. P.U.C. Sheet 89745-E) for the customer's interconnection cohort.
func sceACCPlusAdderDollarsPerKWH(applicationYear string) float64 {
	switch strings.ToLower(strings.TrimSpace(applicationYear)) {
	case "2023":
		return 0.04000
	case "2024":
		return 0.03200
	case "2025":
		return 0.02400
	case "2026", "":
		return 0.01600
	case "2027":
		return 0.00800
	case "non_locked":
		return 0.00000
	default:
		return 0.01600
	}
}

// sceNBTBaseDollarsPerKWH returns the base EEC export credit ($/kWh, before ACC Plus adder)
// for a given calendar year, applicationYear cohort, and Month_DayType_Hour key.
func sceNBTBaseDollarsPerKWH(year int, applicationYear, key string) float64 {
	if year < 2026 {
		year = 2026
	} else if year > 2027 {
		year = 2027
	}

	switch strings.ToLower(strings.TrimSpace(applicationYear)) {
	case "2023", "2024":
		if yearMap, ok := sceNBTPTO12Data[year]; ok {
			if val, ok := yearMap[key]; ok {
				return val
			}
		}
		if val, ok := sceNBTPTO12Data[2026][key]; ok {
			return val
		}
	case "2027", "non_locked":
		if year >= 2027 {
			if val, ok := sceNBT27Data[key]; ok {
				return val
			}
		}
		if val, ok := sceNBTData[2026][key]; ok {
			return val
		}
	default:
		if yearMap, ok := sceNBTData[year]; ok {
			if val, ok := yearMap[key]; ok {
				return val
			}
		}
		if val, ok := sceNBTData[2026][key]; ok {
			return val
		}
	}

	return 0.05 // safe fallback
}

// getSCENBTExportRate returns the total export credit rate ($/kWh, base EEC + ACC Plus adder)
// for SCE Net Billing Tariff (Solar Billing Plan / NEM 3.0) at a given time and applicationYear cohort.
func getSCENBTExportRate(t time.Time, applicationYear string) float64 {
	if ptLocation != nil {
		t = t.In(ptLocation)
	}
	year := t.Year()
	if year < 2026 {
		year = 2026
	} else if year > 2027 {
		year = 2027
	}

	monthStr := t.Format("Jan")

	// Determine if weekend or holiday
	isWeekend := t.Weekday() == time.Saturday || t.Weekday() == time.Sunday
	if !isWeekend {
		holidays := getSCEHolidays(year)
		dateStr := t.Format("2006-01-02")
		for _, h := range holidays {
			if h == dateStr {
				isWeekend = true
				break
			}
		}
	}

	dayType := "Weekday"
	if isWeekend {
		dayType = "Weekend"
	}

	key := fmt.Sprintf("%s_%s_%d", monthStr, dayType, t.Hour())
	return sceNBTBaseDollarsPerKWH(year, applicationYear, key) + sceACCPlusAdderDollarsPerKWH(applicationYear)
}

// getSCEHolidays calculates designated holidays for SCE.
// According to Southern California Edison's official rate schedules (Schedule TOU-D Sheet 9 / 91697-E,
// source: https://www.sce.com/regulatory/regulatory-information/tariff-books/rates-pricing-choices),
// the following 8 holidays are observed:
// 1. New Year's Day (January 1)
// 2. Presidents' Day (Third Monday in February)
// 3. Memorial Day (Last Monday in May)
// 4. Independence Day (July 4)
// 5. Labor Day (First Monday in September)
// 6. Veterans Day (November 11)
// 7. Thanksgiving Day (Fourth Thursday in November)
// 8. Christmas Day (December 25)
//
// Shift rules:
// - If a holiday falls on a Sunday, the following Monday is recognized as the holiday.
// - If a holiday falls on a Saturday, it is not shifted (Saturday is already treated as weekend).
func getSCEHolidays(year int) []string {
	// Helper to shift Sunday holiday to Monday
	shiftSCEHoliday := func(t time.Time) time.Time {
		if t.Weekday() == time.Sunday {
			return t.AddDate(0, 0, 1)
		}
		return t
	}

	holidays := []time.Time{
		shiftSCEHoliday(newYearsDay(year)),
		shiftSCEHoliday(presidentsDay(year)),
		memorialDay(year),
		shiftSCEHoliday(independenceDay(year)),
		laborDay(year),
		shiftSCEHoliday(veteransDay(year)),
		thanksgivingDay(year),
		shiftSCEHoliday(christmasDay(year)),
	}

	return formatHolidays(holidays, year)
}

