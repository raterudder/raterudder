func emitInterfaces(buf *bytes.Buffer, repo *parsedRepo) error {
	if repo.authBodySiteIDField == "" {
		return fmt.Errorf("missing body siteID field in server.authMiddleware")
	}

	strippedSettingsKeys := sortedBoolMapKeys(repo.settingsStrippedJSON)
	goToTSName := buildGoToTSNameMap()
	specs := buildModelSpecs(strippedSettingsKeys, repo.authBodySiteIDField)

	buf.WriteString("export type CredentialsPayload = Record<string, Record<string, string | number | boolean | undefined>>;\n\n")

	for _, spec := range specs {
		if err := emitSingleInterface(buf, repo, spec, goToTSName); err != nil {
			return err
		}
	}
	return nil
}

func sortedBoolMapKeys(m map[string]bool) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func emitSingleInterface(buf *bytes.Buffer, repo *parsedRepo, spec modelSpec, goToTSName map[string]string) error {
	key := spec.goPkg + "." + spec.goName
	st, ok := repo.structs[key]
	if !ok {
		return fmt.Errorf("missing Go struct %s", key)
	}
	fields, err := collectStructFields(repo, st, goToTSName)
	if err != nil {
		return fmt.Errorf("struct %s: %w", key, err)
	}

	filtered := applyModelSpecOverrides(fields, spec)
	fmt.Fprintf(buf, "export interface %s {\n", spec.tsName)
	for _, f := range filtered {
		opt := ""
		if f.optional {
			opt = "?"
		}
		fmt.Fprintf(buf, "    %s%s: %s;\n", f.name, opt, f.tsType)
	}
	buf.WriteString("}\n\n")
	return nil
}

func applyModelSpecOverrides(fields []tsField, spec modelSpec) []tsField {
	var filtered []tsField
	for _, f := range fields {
		if slices.Contains(spec.omitFields, f.name) {
			continue
		}
		if override, ok := spec.fieldOverrides[f.name]; ok {
			f.tsType = override
		}
		filtered = append(filtered, f)
	}
	return append(filtered, spec.extraFields...)
}

func collectStructFields(repo *parsedRepo, ps parsedStruct, goToTSName map[string]string) ([]tsField, error) {
	if ps.structType.Fields == nil {
		return nil, nil
	}

	var result []tsField
	indexByName := make(map[string]int)
	addOrReplace := func(f tsField) {
		if idx, exists := indexByName[f.name]; exists {
			result[idx] = f
			return
		}
		indexByName[f.name] = len(result)
		result = append(result, f)
	}

	for _, field := range ps.structType.Fields.List {
		extracted, err := extractASTField(repo, ps.pkg, field, goToTSName)
		if err != nil {
			return nil, err
		}
		for _, ef := range extracted {
			addOrReplace(ef)
		}
	}
	return result, nil
}

func extractASTField(repo *parsedRepo, pkg string, field *ast.Field, goToTSName map[string]string) ([]tsField, error) {
	if len(field.Names) == 0 {
		return extractEmbeddedField(repo, pkg, field, goToTSName)
	}
	var out []tsField
	for _, ident := range field.Names {
		if !ident.IsExported() {
			continue
		}
		jsonName, optional, skip := parseJSONTagForIdent(field, ident.Name)
		if skip {
			continue
		}
		tsType, err := goExprToTSType(pkg, field.Type, goToTSName)
		if err != nil {
			return nil, fmt.Errorf("field %s: %w", ident.Name, err)
		}
		out = append(out, tsField{name: jsonName, tsType: tsType, optional: optional})
	}
	return out, nil
}

func extractEmbeddedField(repo *parsedRepo, pkg string, field *ast.Field, goToTSName map[string]string) ([]tsField, error) {
	jsonName, optional, skip := parseJSONTag(field)
	if skip {
		return nil, nil
	}
	if jsonName != "" {
		tsType, err := goExprToTSType(pkg, field.Type, goToTSName)
		if err != nil {
			return nil, err
		}
		return []tsField{{name: jsonName, tsType: tsType, optional: optional}}, nil
	}
	embedPkg, embedName, err := resolveEmbeddedStruct(pkg, field.Type)
	if err != nil {
		return nil, err
	}
	embedKey := embedPkg + "." + embedName
	embedStruct, ok := repo.structs[embedKey]
	if !ok {
		return nil, fmt.Errorf("unknown embedded struct %s", embedKey)
	}
	return collectStructFields(repo, embedStruct, goToTSName)
}

func resolveEmbeddedStruct(currentPkg string, expr ast.Expr) (string, string, error) {
	if star, ok := expr.(*ast.StarExpr); ok {
		expr = star.X
	}
	switch e := expr.(type) {
	case *ast.Ident:
		return currentPkg, e.Name, nil
	case *ast.SelectorExpr:
		if pkgIdent, ok := e.X.(*ast.Ident); ok {
			return pkgIdent.Name, e.Sel.Name, nil
		}
	}
	return "", "", fmt.Errorf("unsupported embedded type %T", expr)
}

func parseJSONTag(field *ast.Field) (string, bool, bool) {
	return parseJSONTagForIdent(field, "")
}

func parseJSONTagForIdent(field *ast.Field, fallback string) (string, bool, bool) {
	if field.Tag == nil {
		return fallback, false, false
	}
	rawTag, err := strconv.Unquote(field.Tag.Value)
	if err != nil {
		return fallback, false, false
	}
	tagVal := reflect.StructTag(rawTag).Get("json")
	if tagVal == "-" {
		return "", false, true
	}
	if tagVal == "" {
		return fallback, false, false
	}
	return splitJSONTagValue(tagVal, fallback)
}

func splitJSONTagValue(tagVal, fallback string) (string, bool, bool) {
	parts := strings.Split(tagVal, ",")
	name := parts[0]
	if name == "" {
		name = fallback
	}
	for _, opt := range parts[1:] {
		if opt == "omitempty" || opt == "omitzero" {
			return name, true, false
		}
	}
	return name, false, false
}

func goExprToTSType(currentPkg string, expr ast.Expr, goToTSName map[string]string) (string, error) {
	switch e := expr.(type) {
	case *ast.StarExpr:
		return goExprToTSType(currentPkg, e.X, goToTSName)
	case *ast.Ident:
		return identToTSType(currentPkg, e.Name, goToTSName)
	case *ast.SelectorExpr:
		return selectorToTSType(e, goToTSName)
	case *ast.ArrayType:
		return arrayToTSType(currentPkg, e, goToTSName)
	case *ast.MapType:
		return mapToTSType(currentPkg, e, goToTSName)
	case *ast.InterfaceType:
		return "string | number | boolean", nil
	default:
		return "", fmt.Errorf("unsupported AST type %T", expr)
	}
}

func identToTSType(currentPkg, name string, goToTSName map[string]string) (string, error) {
	switch name {
	case "bool":
		return "boolean", nil
	case "string":
		return "string", nil
	case "any":
		return "string | number | boolean", nil
	}
	if numericGoIdents[name] {
		return "number", nil
	}
	key := currentPkg + "." + name
	if tsName, ok := goToTSName[key]; ok {
		return tsName, nil
	}
	return "", fmt.Errorf("unmapped Go type %s", key)
}

func selectorToTSType(sel *ast.SelectorExpr, goToTSName map[string]string) (string, error) {
	pkgIdent, ok := sel.X.(*ast.Ident)
	if !ok {
		return "", fmt.Errorf("unsupported selector %T", sel.X)
	}
	qual := pkgIdent.Name + "." + sel.Sel.Name
	switch qual {
	case "time.Time":
		return "string", nil
	case "time.Weekday", "time.Duration":
		return "number", nil
	}
	if tsName, ok := goToTSName[qual]; ok {
		return tsName, nil
	}
	return "", fmt.Errorf("unmapped qualified Go type %s", qual)
}

func arrayToTSType(currentPkg string, arr *ast.ArrayType, goToTSName map[string]string) (string, error) {
	if ident, ok := arr.Elt.(*ast.Ident); ok && ident.Name == "byte" {
		return "string", nil
	}
	elemType, err := goExprToTSType(currentPkg, arr.Elt, goToTSName)
	if err != nil {
		return "", err
	}
	if strings.Contains(elemType, " | ") {
		return "(" + elemType + ")[]", nil
	}
	return elemType + "[]", nil
}

func mapToTSType(currentPkg string, m *ast.MapType, goToTSName map[string]string) (string, error) {
	keyType, err := goExprToTSType(currentPkg, m.Key, goToTSName)
	if err != nil {
		return "", err
	}
	valType, err := goExprToTSType(currentPkg, m.Value, goToTSName)
	if err != nil {
		return "", err
	}
	return fmt.Sprintf("Record<%s, %s>", keyType, valType), nil
}

func formatTSString(s string) string {
	escaped := strings.ReplaceAll(s, `\`, `\\`)
	escaped = strings.ReplaceAll(escaped, `'`, `\'`)
	return "'" + escaped + "'"
}
