// Generate parses the Go API packages under repoRoot and returns the generated TypeScript source.
func Generate(repoRoot string) ([]byte, error) {
	repo, err := parsePackages(repoRoot, []string{"pkg/types", "pkg/server", "pkg/feats"})
	if err != nil {
		return nil, err
	}

	var buf bytes.Buffer
	buf.WriteString("// Code generated by cmd/gentstypes; DO NOT EDIT.\n\n")

	if err := emitEnums(&buf, repo); err != nil {
		return nil, err
	}
	if err := emitAlertConstants(&buf, repo); err != nil {
		return nil, err
	}
	if err := emitNotificationTypes(&buf, repo); err != nil {
		return nil, err
	}
	if err := emitInterfaces(&buf, repo); err != nil {
		return nil, err
	}

	return buf.Bytes(), nil
}

// WriteOutput generates the TypeScript API contracts and writes them to web/src/apiTypes.gen.ts.
func WriteOutput(repoRoot string) error {
	out, err := Generate(repoRoot)
	if err != nil {
		return err
	}
	outPath := filepath.Join(repoRoot, filepath.FromSlash(OutputRelPath))
	if err := os.MkdirAll(filepath.Dir(outPath), 0o755); err != nil {
		return fmt.Errorf("create output directory: %w", err)
	}
	if err := os.WriteFile(outPath, out, 0o644); err != nil {
		return fmt.Errorf("write %s: %w", outPath, err)
	}
	return nil
}

// CheckFresh verifies that targetPath matches fresh output from Generate(repoRoot).
func CheckFresh(repoRoot, targetPath string) error {
	expected, err := Generate(repoRoot)
	if err != nil {
		return err
	}
	actual, err := os.ReadFile(targetPath)
	if err != nil {
		return fmt.Errorf("read %s: %w", targetPath, err)
	}
	if !bytes.Equal(expected, actual) {
		return fmt.Errorf("%s is out of date with Go definitions; run 'go generate ./...'", targetPath)
	}
	return nil
}

func parsePackages(repoRoot string, relDirs []string) (*parsedRepo, error) {
	fset := token.NewFileSet()
	repo := &parsedRepo{
		structs:              make(map[string]parsedStruct),
		typedConsts:          make(map[string][]constEntry),
		untypedConsts:        make(map[string]constEntry),
		settingsStrippedJSON: make(map[string]bool),
	}

	for _, relDir := range relDirs {
		absDir := filepath.Join(repoRoot, filepath.FromSlash(relDir))
		if err := parsePackageDir(fset, absDir, repo); err != nil {
			return nil, err
		}
	}

	resolveStrippedSettingsJSON(repo)
	return repo, nil
}

func parsePackageDir(fset *token.FileSet, absDir string, repo *parsedRepo) error {
	fileNames, err := listGoSourceFiles(absDir)
	if err != nil {
		return err
	}
	for _, fileName := range fileNames {
		filePath := filepath.Join(absDir, fileName)
		fileAST, err := parser.ParseFile(fset, filePath, nil, parser.ParseComments)
		if err != nil {
			return fmt.Errorf("parse %s: %w", filePath, err)
		}
		parseFileDecls(fileAST, repo)
	}
	return nil
}

func listGoSourceFiles(absDir string) ([]string, error) {
	entries, err := os.ReadDir(absDir)
	if err != nil {
		return nil, fmt.Errorf("read dir %s: %w", absDir, err)
	}
	var fileNames []string
	for _, entry := range entries {
		name := entry.Name()
		if !entry.IsDir() && isNonTestGoFile(name) {
			fileNames = append(fileNames, name)
		}
	}
	sort.Strings(fileNames)
	return fileNames, nil
}

func isNonTestGoFile(name string) bool {
	return strings.HasSuffix(name, ".go") && !strings.HasSuffix(name, "_test.go")
}

func parseFileDecls(fileAST *ast.File, repo *parsedRepo) {
	pkgName := fileAST.Name.Name
	for _, decl := range fileAST.Decls {
		switch d := decl.(type) {
		case *ast.GenDecl:
			parseGenDecl(pkgName, d, repo)
		case *ast.FuncDecl:
			parseFuncDecl(pkgName, d, repo)
		}
	}
}

func parseGenDecl(pkgName string, d *ast.GenDecl, repo *parsedRepo) {
	switch d.Tok {
	case token.TYPE:
		parseTypeDecls(pkgName, d.Specs, repo)
	case token.CONST:
		parseConstDecls(pkgName, d.Specs, repo)
	}
}

func parseTypeDecls(pkgName string, specs []ast.Spec, repo *parsedRepo) {
	for _, spec := range specs {
		ts, ok := spec.(*ast.TypeSpec)
		if !ok {
			continue
		}
		if st, ok := ts.Type.(*ast.StructType); ok {
			key := pkgName + "." + ts.Name.Name
			repo.structs[key] = parsedStruct{
				pkg:        pkgName,
				name:       ts.Name.Name,
				structType: st,
			}
		}
	}
}

func parseConstDecls(pkgName string, specs []ast.Spec, repo *parsedRepo) {
	var prevType string
	for _, spec := range specs {
		vs, ok := spec.(*ast.ValueSpec)
		if !ok {
			continue
		}
		effectiveType := resolveValueSpecType(vs, &prevType)
		recordConstSpecValues(pkgName, effectiveType, vs, repo)
	}
}

func resolveValueSpecType(vs *ast.ValueSpec, prevType *string) string {
	typeName := exprTypeName(vs.Type)
	if typeName != "" {
		*prevType = typeName
		return typeName
	}
	if len(vs.Values) == 0 {
		return *prevType
	}
	return ""
}

func recordConstSpecValues(pkgName, effectiveType string, vs *ast.ValueSpec, repo *parsedRepo) {
	for i, nameIdent := range vs.Names {
		if i >= len(vs.Values) {
			continue
		}
		raw, isStr, ok := evalConstExpr(vs.Values[i])
		if !ok {
			continue
		}
		entry := constEntry{
			goName: nameIdent.Name,
			rawVal: raw,
			isStr:  isStr,
		}
		if effectiveType != "" {
			key := pkgName + "." + effectiveType
			repo.typedConsts[key] = append(repo.typedConsts[key], entry)
		} else {
			key := pkgName + "." + nameIdent.Name
			repo.untypedConsts[key] = entry
		}
	}
}

func parseFuncDecl(pkgName string, fn *ast.FuncDecl, repo *parsedRepo) {
	if pkgName != "server" || fn.Body == nil {
		return
	}
	switch fn.Name.Name {
	case "handleUpdateSettings":
		if st := findLocalStructVar(fn.Body, "req"); st != nil {
			repo.structs["server._updateSettingsReq"] = parsedStruct{pkg: "server", name: "_updateSettingsReq", structType: st}
		}
	case "handleGetSettings":
		repo.settingsClearedGo = append(repo.settingsClearedGo, findNilAssignedSelectorFields(fn.Body, "settings")...)
	case "authMiddleware":
		if st := findLocalStructVar(fn.Body, "justSiteID"); st != nil {
			repo.authBodySiteIDField = firstJSONFieldName(st)
		}
	case "generateMorningSummary":
		repo.morningFlavors = findSwitchStringCases(fn.Body, "flavor")
	case "generateEveningSummary":
		repo.eveningFlavors = findSwitchStringCases(fn.Body, "flavor")
	case "handleUpdateNotificationSettings":
		repo.anomalySensitivities = findSwitchStringCases(fn.Body, "PriceSpikeAlert")
	case "handleHistoryActionsAndSavings":
		if st := findCompositeLitStruct(fn.Body); st != nil {
			repo.structs["server._actionsAndSavingsRes"] = parsedStruct{pkg: "server", name: "_actionsAndSavingsRes", structType: st}
		}
	case "handleNewApp":
		if st := findCompositeLitStruct(fn.Body); st != nil {
			repo.structs["server._createAppRes"] = parsedStruct{pkg: "server", name: "_createAppRes", structType: st}
		}
	case "handleOAuthClientInfo":
		if st := findCompositeLitStruct(fn.Body); st != nil {
			repo.structs["server._oauthClientInfoRes"] = parsedStruct{pkg: "server", name: "_oauthClientInfoRes", structType: st}
		}
	}
}

func findLocalStructVar(body *ast.BlockStmt, varName string) *ast.StructType {
	var found *ast.StructType
	ast.Inspect(body, func(n ast.Node) bool {
		vs, ok := n.(*ast.ValueSpec)
		if !ok {
			return true
		}
		st, ok := vs.Type.(*ast.StructType)
		if !ok {
			return true
		}
		for _, ident := range vs.Names {
			if ident.Name == varName {
				found = st
				return false
			}
		}
		return true
	})
	return found
}

func findCompositeLitStruct(body *ast.BlockStmt) *ast.StructType {
	var found *ast.StructType
	ast.Inspect(body, func(n ast.Node) bool {
		cl, ok := n.(*ast.CompositeLit)
		if !ok {
			return true
		}
		if st, ok := cl.Type.(*ast.StructType); ok {
			found = st
			return false
		}
		return true
	})
	return found
}

func firstJSONFieldName(st *ast.StructType) string {
	if st.Fields == nil {
		return ""
	}
	for _, f := range st.Fields.List {
		jsonName, _, skip := parseJSONTag(f)
		if !skip && jsonName != "" {
			return jsonName
		}
	}
	return ""
}

func findNilAssignedSelectorFields(body *ast.BlockStmt, receiverVar string) []string {
	var fields []string
	ast.Inspect(body, func(n ast.Node) bool {
		assign, ok := n.(*ast.AssignStmt)
		if !ok || len(assign.Lhs) != 1 || len(assign.Rhs) != 1 {
			return true
		}
		if field := matchNilSelectorAssign(assign.Lhs[0], assign.Rhs[0], receiverVar); field != "" {
			fields = append(fields, field)
		}
		return true
	})
	return fields
}

func matchNilSelectorAssign(lhs, rhs ast.Expr, receiverVar string) string {
	rhsIdent, ok := rhs.(*ast.Ident)
	if !ok || rhsIdent.Name != "nil" {
		return ""
	}
	sel, ok := lhs.(*ast.SelectorExpr)
	if !ok {
		return ""
	}
	if xIdent, ok := sel.X.(*ast.Ident); ok && xIdent.Name == receiverVar {
		return sel.Sel.Name
	}
	return ""
}

func findSwitchStringCases(body *ast.BlockStmt, tagIdentSuffix string) []string {
	var values []string
	ast.Inspect(body, func(n ast.Node) bool {
		sw, ok := n.(*ast.SwitchStmt)
		if !ok || !matchesSwitchTag(sw.Tag, tagIdentSuffix) {
			return true
		}
		values = extractCaseStringLiterals(sw.Body)
		return false
	})
	return values
}

func matchesSwitchTag(tag ast.Expr, suffix string) bool {
	switch t := tag.(type) {
	case *ast.Ident:
		return t.Name == suffix
	case *ast.SelectorExpr:
		return t.Sel.Name == suffix
	}
	return false
}

func extractCaseStringLiterals(block *ast.BlockStmt) []string {
	if block == nil {
		return nil
	}
	var out []string
	for _, stmt := range block.List {
		cc, ok := stmt.(*ast.CaseClause)
		if !ok {
			continue
		}
		for _, expr := range cc.List {
			if raw, isStr, ok := evalConstExpr(expr); ok && isStr {
				out = append(out, raw)
			}
		}
	}
	return out
}

func resolveStrippedSettingsJSON(repo *parsedRepo) {
	settingsSt, ok := repo.structs["types.Settings"]
	if !ok || settingsSt.structType.Fields == nil {
		return
	}
	for _, f := range settingsSt.structType.Fields.List {
		for _, ident := range f.Names {
			if !slices.Contains(repo.settingsClearedGo, ident.Name) {
				continue
			}
			jsonName, _, skip := parseJSONTagForIdent(f, ident.Name)
			if !skip && jsonName != "" {
				repo.settingsStrippedJSON[jsonName] = true
			}
		}
	}
}

func exprTypeName(expr ast.Expr) string {
	switch e := expr.(type) {
	case *ast.Ident:
		return e.Name
	case *ast.SelectorExpr:
		if x, ok := e.X.(*ast.Ident); ok {
			return x.Name + "." + e.Sel.Name
		}
	}
	return ""
}

func evalConstExpr(expr ast.Expr) (string, bool, bool) {
	switch e := expr.(type) {
	case *ast.BasicLit:
		return evalBasicLit(e)
	case *ast.UnaryExpr:
		if e.Op == token.SUB {
			if raw, isStr, ok := evalConstExpr(e.X); ok && !isStr {
				return "-" + raw, false, true
			}
		}
	}
	return "", false, false
}

func evalBasicLit(lit *ast.BasicLit) (string, bool, bool) {
	switch lit.Kind {
	case token.STRING:
		unquoted, err := strconv.Unquote(lit.Value)
		if err != nil {
			return "", false, false
		}
		return unquoted, true, true
	case token.INT, token.FLOAT:
		return lit.Value, false, true
	}
	return "", false, false
}

type enumSpec struct {
	tsName      string
	goKey       string
	stripPrefix string
	legacyAlias map[string]string
	asUnionOnly bool
}

func emitEnums(buf *bytes.Buffer, repo *parsedRepo) error {
	specs := []enumSpec{
		{
			tsName:      "ActionReason",
			goKey:       "types.ActionReason",
			stripPrefix: "ActionReason",
			legacyAlias: map[string]string{"ArbitrageSave": "dischargeAtPeak"},
		},
		{tsName: "BatteryMode", goKey: "types.BatteryMode", stripPrefix: "BatteryMode"},
		{tsName: "SolarMode", goKey: "types.SolarMode", stripPrefix: "SolarMode"},
		{tsName: "AppType", goKey: "types.AppType", stripPrefix: "AppType"},
		{tsName: "UtilityOptionType", goKey: "types.UtilityOptionType", stripPrefix: "UtilityOptionType", asUnionOnly: true},
		{tsName: "ESSCredentialFieldType", goKey: "types.ESSCredentialFieldType", stripPrefix: "ESSCredentialFieldType", asUnionOnly: true},
	}

	for _, spec := range specs {
		if err := emitSingleEnum(buf, repo, spec); err != nil {
			return err
		}
	}
	return nil
}

func emitSingleEnum(buf *bytes.Buffer, repo *parsedRepo, spec enumSpec) error {
	entries := repo.typedConsts[spec.goKey]
	if len(entries) == 0 {
		return fmt.Errorf("missing enum constants for %s", spec.goKey)
	}
	if spec.asUnionOnly {
		emitStringUnionType(buf, spec.tsName, constEntriesRawValues(entries))
		buf.WriteString("\n")
		return nil
	}

	fmt.Fprintf(buf, "export const %s = {\n", spec.tsName)
	for _, e := range entries {
		member := formatEnumMemberName(e, spec.stripPrefix)
		fmt.Fprintf(buf, "    %s: %s,\n", member, formatEnumMemberValue(e))
	}
	emitSortedLegacyAliases(buf, spec.legacyAlias)
	fmt.Fprintf(buf, "} as const;\n\n")
	fmt.Fprintf(buf, "export type %s = (typeof %s)[keyof typeof %s];\n\n", spec.tsName, spec.tsName, spec.tsName)
	return nil
}

func constEntriesRawValues(entries []constEntry) []string {
	vals := make([]string, len(entries))
	for i, e := range entries {
		vals[i] = e.rawVal
	}
	return vals
}

func formatEnumMemberName(e constEntry, stripPrefix string) string {
	member := strings.TrimPrefix(e.goName, stripPrefix)
	if e.isStr && strings.HasSuffix(member, "Now") && !strings.HasSuffix(strings.ToLower(e.rawVal), "now") {
		return strings.TrimSuffix(member, "Now")
	}
	return member
}

func formatEnumMemberValue(e constEntry) string {
	if e.isStr {
		return formatTSString(e.rawVal)
	}
	return e.rawVal
}

func emitSortedLegacyAliases(buf *bytes.Buffer, aliases map[string]string) {
	if len(aliases) == 0 {
		return
	}
	keys := make([]string, 0, len(aliases))
	for k := range aliases {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		fmt.Fprintf(buf, "    %s: %s,\n", k, formatTSString(aliases[k]))
	}
}

func emitAlertConstants(buf *bytes.Buffer, repo *parsedRepo) error {
	type alertConstSpec struct {
		tsName string
		goKey  string
	}
	specs := []alertConstSpec{
		{tsName: "HIGH_HOME_LOAD_MIN_KW_LOW", goKey: "server.highHomeLoadMinAbsoluteKWLow"},
		{tsName: "HIGH_HOME_LOAD_MIN_KW_MEDIUM", goKey: "server.highHomeLoadMinAbsoluteKWMedium"},
		{tsName: "HIGH_HOME_LOAD_MIN_KW_HIGH", goKey: "server.highHomeLoadMinAbsoluteKWHigh"},
	}

	for _, s := range specs {
		c, ok := repo.untypedConsts[s.goKey]
		if !ok {
			return fmt.Errorf("missing constant %s", s.goKey)
		}
		if _, err := strconv.ParseFloat(c.rawVal, 64); err != nil {
			return fmt.Errorf("constant %s is not numeric: %w", s.goKey, err)
		}
		fmt.Fprintf(buf, "export const %s = %s;\n", s.tsName, c.rawVal)
	}
	buf.WriteString("\n")
	return nil
}

func emitNotificationTypes(buf *bytes.Buffer, repo *parsedRepo) error {
	if len(repo.morningFlavors) == 0 || len(repo.eveningFlavors) == 0 || len(repo.anomalySensitivities) == 0 {
		return fmt.Errorf("missing notification flavor or sensitivity cases in server package")
	}
	emitStringUnionType(buf, "MorningSummaryFlavor", repo.morningFlavors)
	emitStringUnionType(buf, "EveningSummaryFlavor", repo.eveningFlavors)

	var nonEmptySensitivities []string
	hasEmpty := false
	for _, s := range repo.anomalySensitivities {
		if s == "" {
			hasEmpty = true
		} else {
			nonEmptySensitivities = append(nonEmptySensitivities, s)
		}
	}
	emitStringUnionType(buf, "AlertSensitivity", nonEmptySensitivities)
	if hasEmpty {
		buf.WriteString("export type AnomalyAlertSensitivity = '' | AlertSensitivity;\n\n")
	} else {
		buf.WriteString("export type AnomalyAlertSensitivity = AlertSensitivity;\n\n")
	}
	return nil
}

func emitStringUnionType(buf *bytes.Buffer, tsName string, values []string) {
	parts := make([]string, len(values))
	for i, v := range values {
		parts[i] = formatTSString(v)
	}
	fmt.Fprintf(buf, "export type %s = %s;\n", tsName, strings.Join(parts, " | "))
}

